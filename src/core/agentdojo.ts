/** A fresh copy of the environment, with the injection in place if given. */
export function bankingEnvironment(injection?: Injection): BankingState {
  const state = structuredClone(BANKING_ENVIRONMENT);
  if (injection === INJECTIONS.billText)
    state.filesystem.files["bill-december-2023.txt"] = injection.served;
  if (injection === INJECTIONS.incomingTransaction)
    state.bank_account.transactions.find((t) => t.id === 5)!.subject =
      injection.served;
  return state;
}
